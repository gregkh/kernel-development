#!/usr/bin/env python3
"""Sanity checks for the Linux kernel development slide repository.

This is a read-only tool: it never modifies, regenerates or rewrites any
slide deck, image or data file.  It reports:

  * structural problems in the ODP decks (corrupt zip, bad mimetype,
    missing manifest entries, unparseable content.xml)
  * structural problems in the exported PDFs (bad header / trailer)
  * stale PDF exports (page count no longer matches the deck)
  * syntax errors in the Perl and Ruby helper scripts
  * committed build artifacts, lock files and other cruft
  * duplicate files and trivial text hygiene issues

Usage:
    scripts/check_repo.py [--root DIR] [--strict] [--quiet]

Exit status:
    0   no errors (warnings may still have been printed)
    1   at least one error, or (with --strict) at least one warning

Perl and Ruby checks are skipped with a notice when the interpreter is not
installed, so the script is safe to run on a bare checkout.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile
import zlib
from collections import defaultdict

ODP_MIMETYPE = "application/vnd.oasis.opendocument.presentation"
MANIFEST_NS = "urn:oasis:names:tc:opendocument:xmlns:manifest:1.0"

# Files that are generated by the helper scripts and must never be committed.
GENERATED = [
    "my_fruity_graph.png",
    ".bundle",
    "vendor/bundle",
    "__pycache__",
    "*.pyc",
]

# Extensions treated as text for the (informational) hygiene check.
TEXT_EXTENSIONS = {
    ".txt", ".rb", ".ruby", ".pl", ".graph", ".md", ".yml", ".yaml",
    ".svg", ".eps", ".dot", ".lock", ".tex",
}
TEXT_NAMES = {
    "README", "Gemfile", "Gemfile.lock", "NOTES", "quote", "do_dot",
    "make_dot", "totals", "changes", "LICENSE",
}

# Directories whose historical files are left exactly as they are.
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".bundle"}


class Report:
    """Collects errors / warnings / informational notices."""

    def __init__(self, quiet: bool = False) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.notices: list[str] = []
        self.quiet = quiet

    def error(self, msg: str) -> None:
        self.errors.append(msg)
        print(f"ERROR:   {msg}")

    def warn(self, msg: str) -> None:
        self.warnings.append(msg)
        print(f"warning: {msg}")

    def info(self, msg: str) -> None:
        self.notices.append(msg)
        print(f"note:    {msg}")

    def ok(self, msg: str) -> None:
        """Per-file success line, hidden by --quiet."""
        if not self.quiet:
            print(f"  {msg}")

    def section(self, title: str) -> None:
        print(f"\n== {title}")


def walk(root: str):
    """Yield every file in the tree, skipping VCS / build directories."""
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            yield os.path.join(dirpath, name)


def rel(root: str, path: str) -> str:
    return os.path.relpath(path, root)


def git_tracked(root: str) -> list[str] | None:
    """Files known to git, or None when this is not a git checkout."""
    if not os.path.isdir(os.path.join(root, ".git")):
        return None
    try:
        out = subprocess.run(
            ["git", "ls-files", "-z"],
            cwd=root, check=True, capture_output=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    return [os.path.join(root, p.decode("utf-8", "replace"))
            for p in out.split(b"\0") if p]


def git_ignores(root: str, path: str) -> bool | None:
    try:
        res = subprocess.run(
            ["git", "check-ignore", "-q", path],
            cwd=root, capture_output=True,
        )
    except OSError:
        return None
    return res.returncode == 0


def pdf_page_count(path: str) -> int:
    """Best-effort page count using only the standard library.

    PDFs in this repo mix uncompressed page trees with compressed object
    streams, so the count is taken as the maximum of three independent
    readings.  This was validated against pypdf on every PDF in the repo.
    """
    with open(path, "rb") as handle:
        data = handle.read()

    raw = len(re.findall(rb"/Type\s*/Page[^s]", data))

    decompressed = bytearray()
    for match in re.finditer(rb"stream\r?\n", data):
        start = match.end()
        end = data.find(b"endstream", start)
        if end == -1:
            continue
        chunk = data[start:end]
        try:
            decompressed += zlib.decompress(chunk)
        except zlib.error:
            decompressed += chunk

    in_streams = len(re.findall(rb"/Type\s*/Page[^s]", bytes(decompressed)))
    counts = [int(c) for c in
              re.findall(rb"/Count\s+(\d+)", data + bytes(decompressed))]

    return max(raw, in_streams, max(counts, default=0))


def odp_slide_count(path: str) -> int:
    with zipfile.ZipFile(path) as zf:
        content = zf.read("content.xml").decode("utf-8", "replace")
    return len(re.findall(r"<draw:page[\s>]", content))


def check_odp(root: str, rep: Report) -> dict[str, int]:
    rep.section("ODP deck integrity")
    slides: dict[str, int] = {}
    found = 0
    for path in walk(root):
        if not path.endswith(".odp"):
            continue
        found += 1
        name = rel(root, path)
        try:
            with zipfile.ZipFile(path) as zf:
                bad = zf.testzip()
                if bad is not None:
                    rep.error(f"{name}: corrupt entry {bad}")
                    continue
                names = zf.namelist()

                if not names or names[0] != "mimetype":
                    rep.error(f"{name}: 'mimetype' is not the first zip entry")
                else:
                    info = zf.getinfo("mimetype")
                    if info.compress_type != zipfile.ZIP_STORED:
                        rep.error(f"{name}: 'mimetype' must be stored uncompressed")
                    mimetype = zf.read("mimetype").decode("ascii", "replace")
                    if mimetype != ODP_MIMETYPE:
                        rep.error(f"{name}: unexpected mimetype {mimetype!r}")

                if "content.xml" not in names:
                    rep.error(f"{name}: missing content.xml")
                    continue

                # Every file listed in the manifest must really be present.
                if "META-INF/manifest.xml" in names:
                    missing = [
                        entry.get(f"{{{MANIFEST_NS}}}full-path")
                        for entry in ET.fromstring(zf.read("META-INF/manifest.xml"))
                        if entry.tag == f"{{{MANIFEST_NS}}}file-entry"
                    ]
                    missing = [m for m in missing
                               if m and not m.endswith("/") and m not in names]
                    if missing:
                        rep.error(
                            f"{name}: manifest references missing file(s): "
                            f"{', '.join(sorted(missing))}")

                try:
                    ET.fromstring(zf.read("content.xml"))
                except ET.ParseError as exc:
                    rep.error(f"{name}: content.xml is not well-formed XML ({exc})")
                    continue

                count = odp_slide_count(path)
                slides[name] = count

                empty = [p for p in names
                         if p.startswith("Pictures/") and zf.getinfo(p).file_size == 0]
                if empty:
                    rep.warn(f"{name}: empty image(s) in Pictures/: "
                             f"{', '.join(sorted(empty))}")

        except zipfile.BadZipFile as exc:
            rep.error(f"{name}: not a readable ODP/zip file ({exc})")
            continue

        rep.ok(f"{name}: OK, {slides.get(name, 0)} slides")
    if found == 0:
        rep.warn("no .odp decks found")
    return slides


def check_pdf(root: str, rep: Report) -> dict[str, int]:
    rep.section("PDF export integrity")
    pages: dict[str, int] = {}
    found = 0
    for path in walk(root):
        if not path.endswith(".pdf"):
            continue
        found += 1
        name = rel(root, path)
        with open(path, "rb") as handle:
            head = handle.read(8)
            handle.seek(0)
            blob = handle.read()
        if not head.startswith(b"%PDF-"):
            rep.error(f"{name}: missing %PDF- header")
            continue
        if b"%%EOF" not in blob[-2048:]:
            rep.error(f"{name}: missing %%EOF trailer (file may be truncated)")
            continue
        version = head[5:8].decode("ascii", "replace")
        count = pdf_page_count(path)
        pages[name] = count
        rep.ok(f"{name}: OK, PDF {version}, {count} pages")
    if found == 0:
        rep.warn("no .pdf files found")
    return pages


def check_export_sync(root: str, slides: dict[str, int], pages: dict[str, int],
                      rep: Report) -> None:
    """Flag PDFs whose page count no longer matches the source deck."""
    rep.section("PDF exports vs. source decks")
    stale = 0
    for deck, count in sorted(slides.items()):
        export = deck[:-4] + ".pdf"
        if export not in pages:
            continue
        pdf_pages = pages[export]
        if pdf_pages == count:
            rep.ok(f"{export}: in sync ({count} pages)")
            continue
        stale += 1
        rep.warn(f"{export}: stale export, deck has {count} slides but the PDF "
                 f"has {pdf_pages} pages - re-export from {deck}")
    if stale:
        rep.info(f"{stale} PDF export(s) are older than their deck; the decks "
                 f"themselves are fine, only the exported copies lag behind")


def run_syntax_check(root: str, rep: Report, title: str, extensions: set[str],
                     interpreter: str, flag: str = "-c") -> None:
    rep.section(title)
    files = [p for p in walk(root) if os.path.splitext(p)[1] in extensions]
    if not files:
        rep.info(f"no {'/'.join(sorted(extensions))} files found")
        return
    try:
        subprocess.run([interpreter, "-v"], capture_output=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        rep.info(f"{interpreter} not installed - skipping {len(files)} file(s)")
        return
    for path in files:
        name = rel(root, path)
        res = subprocess.run([interpreter, flag, name], cwd=root,
                             capture_output=True, text=True)
        if res.returncode == 0:
            rep.ok(f"{name}: syntax OK")
        else:
            rep.error(f"{name}: {interpreter} {flag} failed\n"
                      f"          {(res.stderr or res.stdout).strip()}")


def check_cruft(root: str, rep: Report) -> None:
    rep.section("Build artifacts and editor cruft")
    dirty = 0
    for path in walk(root):
        base = os.path.basename(path)
        name = rel(root, path)
        if base.startswith(".~lock."):
            rep.error(f"{name}: LibreOffice lock file should not be committed")
            dirty += 1
        elif base in GENERATED or base.endswith((".pyc", ".orig", ".rej")):
            rep.error(f"{name}: generated artifact should not be committed")
            dirty += 1
    if not dirty:
        rep.ok("clean")


def check_gitignore(root: str, rep: Report) -> None:
    rep.section("Generated output coverage in .gitignore")
    targets = ["my_fruity_graph.png", "graphs/my_fruity_graph.png",
               ".bundle/config", "__pycache__/x.pyc", "foo.pyc"]
    missing = []
    for target in targets:
        ignored = git_ignores(root, target)
        if ignored is False:
            missing.append(target)
    if missing:
        rep.warn("these generated paths are not ignored by git: "
                 + ", ".join(missing))
    else:
        rep.ok("generated outputs are ignored")


def check_duplicates(root: str, rep: Report) -> None:
    rep.section("Duplicate files")
    by_hash: dict[str, list[str]] = defaultdict(list)
    for path in walk(root):
        if os.path.getsize(path) == 0:
            continue
        digest = hashlib.md5()
        try:
            with open(path, "rb") as handle:
                for chunk in iter(lambda: handle.read(1 << 20), b""):
                    digest.update(chunk)
        except OSError:
            continue
        by_hash[digest.hexdigest()].append(rel(root, path))
    dupes = [sorted(paths) for paths in by_hash.values() if len(paths) > 1]

    # old/ is a historical archive: each conference subdir carries its own copy
    # of the same graphs and stock images, so duplicates there are expected.
    archive = [paths for paths in dupes
               if all(p.startswith("old" + os.sep) for p in paths)]
    real = [paths for paths in dupes if paths not in archive]

    for paths in sorted(real):
        rep.warn("identical files: " + ", ".join(paths))
    if archive:
        rep.info(f"old/ archive holds {len(archive)} group(s) of duplicated "
                 f"files (expected: one copy per conference)")

    if not real:
        rep.ok("no unexpected duplicates")


def check_zero_byte(root: str, rep: Report) -> None:
    rep.section("Empty files")
    empty = [rel(root, p) for p in walk(root) if os.path.getsize(p) == 0]
    tracked = git_tracked(root)
    if tracked is not None:
        empty = [e for e in empty if os.path.join(root, e) in set(tracked)]
    for name in empty:
        rep.warn(f"{name}: file is empty")
    if not empty:
        rep.ok("none")


def check_text_hygiene(root: str, rep: Report) -> None:
    rep.section("Text file hygiene (informational)")
    problems = 0
    for path in walk(root):
        name = rel(root, path)
        ext = os.path.splitext(path)[1]
        if ext not in TEXT_EXTENSIONS and os.path.basename(path) not in TEXT_NAMES:
            continue
        try:
            with open(path, "rb") as handle:
                data = handle.read()
        except OSError:
            continue
        if not data:
            continue
        notes = []
        if not data.endswith(b"\n"):
            notes.append("no trailing newline")
        if b"\r\n" in data:
            notes.append("CRLF line endings")
        trailing = sum(1 for line in data.split(b"\n")
                       if line.rstrip(b" \t") != line)
        if trailing:
            notes.append(f"trailing whitespace on {trailing} line(s)")
        if notes:
            problems += 1
            rep.warn(f"{name}: " + ", ".join(notes))
    if not problems:
        rep.ok("clean")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", default=None,
                        help="repository root (default: parent of scripts/)")
    parser.add_argument("--strict", action="store_true",
                        help="treat warnings as errors")
    parser.add_argument("--quiet", "-q", action="store_true",
                        help="only print problems, not per-file OK lines")
    args = parser.parse_args(argv)

    if args.root:
        root = os.path.abspath(args.root)
    else:
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if not os.path.isdir(root):
        print(f"error: {root} is not a directory", file=sys.stderr)
        return 2

    rep = Report(quiet=args.quiet)
    if not rep.quiet:
        print(f"Checking repository at {root}")

    slides = check_odp(root, rep)
    pages = check_pdf(root, rep)
    check_export_sync(root, slides, pages, rep)
    run_syntax_check(root, rep, "Perl script syntax", {".pl"}, "perl")
    run_syntax_check(root, rep, "Ruby script syntax", {".rb", ".ruby"}, "ruby")
    check_cruft(root, rep)
    check_gitignore(root, rep)
    check_duplicates(root, rep)
    check_zero_byte(root, rep)
    check_text_hygiene(root, rep)

    errors = len(rep.errors)
    warnings = len(rep.warnings)
    if args.strict:
        errors += warnings
        warnings = 0

    print()
    print(f"Summary: {errors} error(s), {warnings} warning(s)")
    if errors:
        print("FAILED - see the errors above")
        return 1
    if warnings:
        print("OK with warnings")
    else:
        print("OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
